const make = (
  id: TraitKind,
  name: string,
  type: "faction" | "class",
  icon: string,
  color: number,
  description: string,
  tiers: [string, number, number?, number?][],
): TraitDefinition => ({
  id,
  name,
  type,
  icon,
  color,
  description,
  tiers: tiers.map(([text, value, secondary, interval], i) => ({
    count: i === 0 ? 2 : 4,
    description: text,
    effect: {
      ...timing[id],
      kind: id,
      value,
      secondary,
      interval: interval ?? timing[id]?.interval,
    },
  })),
});
